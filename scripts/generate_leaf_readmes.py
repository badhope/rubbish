#!/usr/bin/env python3
"""Generate a human-readable README.md for every leaf paper directory.

Every paper in the corpus lives in a 6-level taxonomy path:

    papers/<field>/<year>/<category>/<topic>/<tier>/<method>/<industry>/<leaf>/

The leaf directory holds a machine-readable ``metadata.json``.  This script
turns that metadata into a single ``README.md`` per leaf so the directory is
self-describing: the README contains the paper's title, authors, year,
journal/tier, taxonomy position (where it sits in the tree), canonical links
(DOI, publisher landing page, bundled PDF), the abstract and the keywords.

The output is regenerated from the metadata on every run and is idempotent.
A ``GENERATED_MARKER`` comment is added at the top so accidental hand-edits
are easy to spot.

Usage::

    python3 scripts/generate_leaf_readmes.py            # write all leaves
    python3 scripts/generate_leaf_readmes.py --check   # exit 1 if stale
    python3 scripts/generate_leaf_readmes.py --force   # ignore marker
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
PAPERS = ROOT / "papers"
REPO_URL = "https://github.com/badhope/ScholarLib"
SITE_BASE = "https://badhope.github.io/ScholarLib"

GENERATED_MARKER = "<!-- generated by scripts/generate_leaf_readmes.py; do not edit by hand -->"


# --- Markdown table padding ---------------------------------------------------
# Prettier reformats Markdown tables so columns line up; if we don't do the
# same while emitting, every regeneration trips `npm run format:check`. The
# logic below mirrors the behaviour in scripts/generate_topic_pages.py.

_TABLE_SEP_RE = re.compile(r"^\s*\|?[\s:\-|]+\|?\s*$")


def _pad_table_block(block: list[str]) -> list[str]:
    # Parse every row into its cell contents.
    rows: list[list[str]] = []
    for line in block:
        stripped = line.strip()
        if stripped.startswith("|"):
            stripped = stripped[1:]
        if stripped.endswith("|"):
            stripped = stripped[:-1]
        cells = [c.strip() for c in stripped.split("|")]
        rows.append(cells)
    if not rows:
        return block
    width = max(len(r) for r in rows)
    for r in rows:
        if len(r) < width:
            r.extend([""] * (width - len(r)))
    col_widths = [max(len(r[c]) for r in rows) for c in range(width)]
    out: list[str] = []
    for idx, r in enumerate(rows):
        padded = " | ".join(r[c].ljust(col_widths[c]) for c in range(width))
        out.append(f"| {padded} |")
        if idx == 0:
            sep = " | ".join("-" * col_widths[c] for c in range(width))
            out.append(f"| {sep} |")
    return out


def _pad_markdown_tables(text: str) -> str:
    lines = text.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if "|" in line and i + 1 < len(lines) and _TABLE_SEP_RE.match(lines[i + 1]):
            block: list[str] = [line]
            j = i + 1
            while j < len(lines) and lines[j].lstrip().startswith("|") and lines[j].strip().endswith("|"):
                block.append(lines[j])
                j += 1
            out.extend(_pad_table_block(block))
            i = j
            continue
        out.append(line)
        i += 1
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


def _read_meta(meta_path: Path) -> dict[str, Any] | None:
    try:
        return json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _format_authors(authors: list[str]) -> str:
    if not authors:
        return "—"
    if len(authors) == 1:
        return authors[0]
    if len(authors) == 2:
        return f"{authors[0]} & {authors[1]}"
    return ", ".join(authors[:-1]) + f", & {authors[-1]}"


def _position(meta_path: Path, papers_root: Path | None = None) -> dict[str, str]:
    """Extract taxonomy position from the metadata path.

    The taxonomy is:
        papers/<field>/<year>/<category>/<topic>/<tier>/<method>/<industry>/<leaf>
    The taxonomy slices below ``papers/`` are the parts we surface here.
    """
    root = papers_root or PAPERS
    rel_to_papers = meta_path.parent.relative_to(root)
    parts = rel_to_papers.parts
    return {
        "field": parts[0] if len(parts) > 0 else "—",
        "year": parts[1] if len(parts) > 1 else "—",
        "category": parts[2] if len(parts) > 2 else "—",
        "topic": parts[3] if len(parts) > 3 else "—",
        "tier": parts[4] if len(parts) > 4 else "—",
        "method": parts[5] if len(parts) > 5 else "—",
        "industry": parts[6] if len(parts) > 6 else "—",
        "leaf": parts[7] if len(parts) > 7 else "—",
    }


def _volume_issue_pages(meta: dict[str, Any]) -> str:
    vol = meta.get("volume")
    num = meta.get("number")
    pages = meta.get("pages")
    pieces: list[str] = []
    if vol and num:
        pieces.append(f"{vol}({num})")
    elif vol:
        pieces.append(str(vol))
    if pages:
        pieces.append(f"pp. {pages}")
    return ", ".join(pieces)


def _links_block(meta: dict[str, Any], rel: Path, meta_path: Path) -> list[str]:
    """Return a list of markdown link lines for the 'Where to read it' section."""
    lines: list[str] = []
    doi = (meta.get("doi") or "").strip()
    if doi:
        lines.append(f"- [DOI landing page](https://doi.org/{doi}) — `{doi}`")

    pub = (meta.get("publisher_url") or "").strip()
    if pub and pub != f"https://doi.org/{doi}":
        lines.append(f"- [Publisher page]({pub})")

    repo_url = f"{REPO_URL}/tree/main/{rel.as_posix()}"
    lines.append(f"- [Repository folder]({repo_url})")
    lines.append(f"- [metadata.json]({repo_url}/metadata.json)")

    if meta.get("has_pdf"):
        pdf_path = rel / "paper.pdf"
        lines.append(f"- [📄 PDF on the site]({SITE_BASE}/{rel.as_posix()}/paper.pdf)")
        lines.append(f"- [📄 PDF in the repo]({REPO_URL}/blob/main/{pdf_path.as_posix()})")
    else:
        lines.append("- 📄 PDF: not bundled in this repository (publisher access only)")

    bib = rel / "paper.bib"
    bib_full = meta_path.parent / "paper.bib"
    if bib_full.exists():
        lines.append(f"- [BibTeX citation]({REPO_URL}/blob/main/{bib.as_posix()})")

    return lines


def _render(meta: dict[str, Any], meta_path: Path,
            base_dir: Path | None = None,
            papers_root: Path | None = None) -> str:
    base = base_dir or ROOT
    try:
        rel = meta_path.parent.relative_to(base)
    except ValueError:
        # meta_path lives outside the project root (e.g. in a test fixture).
        # Fall back to the path relative to the nearest common ancestor
        # so the rendered README still shows the taxonomy, not an absolute
        # /tmp path.
        rel = meta_path.parent
    pos = _position(meta_path, papers_root=papers_root)
    title = (meta.get("title") or "Untitled").strip()
    authors = _format_authors(meta.get("authors") or [])
    year = meta.get("year", "—")
    journal = (meta.get("journal") or "—").strip()
    tier = (meta.get("journal_tier") or "—").strip()
    abstract = (meta.get("abstract") or "").strip()
    keywords = meta.get("keywords") or []
    doi = (meta.get("doi") or "").strip()
    is_synth = bool(meta.get("synthetic"))
    is_verified = bool(meta.get("doi_verified"))
    has_pdf = bool(meta.get("has_pdf"))

    status_flags: list[str] = []
    if is_synth:
        status_flags.append("⚠️ placeholder entry (metadata is a synthetic template)")
    if is_verified:
        status_flags.append("✓ DOI verified live")
    if has_pdf:
        status_flags.append("📄 full PDF bundled")

    out: list[str] = []
    out.append(GENERATED_MARKER)
    # Prettier wants a blank line between the marker and the heading.
    out.append("")
    out.append(f"# {title}")
    out.append("")

    if status_flags:
        out.append("> " + " · ".join(status_flags))
        out.append("")

    # Quick-glance citation table
    out.append("| Field | Value |")
    out.append("| --- | --- |")
    out.append(f"| **Authors** | {authors} |")
    out.append(f"| **Year** | {year} |")
    citation_cell = journal
    if tier and tier != "—":
        citation_cell += f" ({tier})"
    vol_iss = _volume_issue_pages(meta)
    if vol_iss:
        citation_cell += f", {vol_iss}"
    out.append(f"| **Journal** | {citation_cell} |")
    out.append(f"| **DOI** | {f'[{doi}](https://doi.org/{doi})' if doi else '—'} |")
    out.append("")

    # Taxonomy position (the "where in the corpus" the user asked for)
    out.append("## Where it sits in the corpus")
    out.append("")
    out.append("| Level | Value |")
    out.append("| --- | --- |")
    for key in ("field", "year", "category", "topic", "tier", "method", "industry", "leaf"):
        out.append(f"| {key} | `{pos[key]}` |")
    out.append("")

    # Links (the "links" the user asked for)
    out.append("## Where to read it")
    out.append("")
    out.extend(_links_block(meta, rel, meta_path))
    out.append("")

    # Abstract / intro
    if abstract:
        out.append("## Abstract")
        out.append("")
        out.append(abstract)
        out.append("")

    if keywords:
        out.append("## Keywords")
        out.append("")
        out.append(", ".join(f"`{kw}`" for kw in keywords))
        out.append("")

    # Provenance
    submitted_by = meta.get("submitted_by")
    date_added = meta.get("date_added")
    if submitted_by or date_added:
        out.append("## Provenance")
        out.append("")
        if submitted_by:
            out.append(f"- Submitted by: `{submitted_by}`")
        if date_added:
            out.append(f"- Date added: `{date_added}`")
        out.append("")

    out.append("---")
    # Prettier wants a blank line between the `---` rule and the italic
    # attribution that follows.
    out.append("")
    out.append(
        f"_Path: `{rel.as_posix()}` · "
        f"Source metadata: [`metadata.json`]({REPO_URL}/blob/main/{rel.as_posix()}/metadata.json)_"
    )
    out.append("")
    raw = "\n".join(out)
    return _pad_markdown_tables(raw)


def _is_generated(text: str) -> bool:
    return GENERATED_MARKER in text


def main(argv: list[str] | None = None, papers_dir: Path | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if any README is missing or stale")
    parser.add_argument("--force", action="store_true",
                        help="overwrite even already-generated READMEs")
    args = parser.parse_args(argv)

    papers_root = papers_dir or PAPERS
    if not papers_root.exists():
        print(f"[generate_leaf_readmes] no {papers_root.name}/ directory; nothing to do", file=sys.stderr)
        return 0

    meta_paths = sorted(papers_root.rglob("metadata.json"))
    if not meta_paths:
        print(f"[generate_leaf_readmes] no metadata.json found under {papers_root}", file=sys.stderr)
        return 0

    written = 0
    skipped = 0
    stale: list[str] = []
    for meta_path in meta_paths:
        meta = _read_meta(meta_path)
        if meta is None:
            print(f"[generate_leaf_readmes] skip (bad json): {meta_path}", file=sys.stderr)
            continue
        readme_path = meta_path.parent / "README.md"
        target = _render(meta, meta_path, papers_root=papers_root)
        if readme_path.exists() and _is_generated(readme_path.read_text(encoding="utf-8")):
            if not args.force and readme_path.read_text(encoding="utf-8") == target:
                skipped += 1
                continue
        if args.check:
            try:
                stale.append(str(readme_path.relative_to(ROOT)))
            except ValueError:
                stale.append(str(readme_path))
            continue
        readme_path.write_text(target, encoding="utf-8")
        written += 1

    if args.check:
        if stale:
            print(f"[generate_leaf_readmes] {len(stale)} README(s) out of date:", file=sys.stderr)
            for s in stale:
                print(f"  - {s}", file=sys.stderr)
            return 1
        print(f"[generate_leaf_readmes] all {len(meta_paths)} README(s) up to date")
        return 0

    print(f"[generate_leaf_readmes] wrote {written}, up-to-date {skipped}, total {len(meta_paths)}")
    return 0


# Backwards-compatible alias used by the test suite to inject a custom tree.
def main_with_args(argv: list[str] | None = None, papers_dir: Path | None = None) -> int:
    return main(argv=argv, papers_dir=papers_dir)


if __name__ == "__main__":
    sys.exit(main())
