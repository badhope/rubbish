def _render_stub(
    area: str,
    slug: str,
    zh_title: str,
    zh_desc: str,
    en_title: str,
    en_path: str,
) -> str:
    """Render one zh stub page. ``en_path`` is the URL of the English
    counterpart (e.g. /papers/computer-science/ai-safety-alignment).

    Note: we use ``_..._`` for emphasis rather than ``*...*`` because
    Prettier rewrites the latter to the former, and the drift check
    compares byte-for-byte with the on-disk file.
    """
    return (
        f"# {zh_title}\n\n"
        f"{GENERATED_MARKER}"
        f"{zh_desc}\n\n"
        f"## 翻译状态\n\n"
        f"本页面的中文版本尚未提供。完整内容（_《{en_title}》_）请参阅 "
        f"[{en_title}（English）]({en_path})。\n\n"
        f"如果你愿意协助翻译本页（保留链接、表格、参考文献格式），欢迎在 "
        f"[GitHub 仓库](https://github.com/badhope/ScholarLib/blob/main/CONTRIBUTING.md) "
        f"提交 PR。\n"
    )


def _read_en_title(en_path: Path) -> str:
    """Extract the H1 title from an English topic page."""
    if not en_path.is_file():
        return en_path.stem.replace("-", " ").title()
    text = en_path.read_text(encoding="utf-8")
    for line in text.splitlines():
        m = re.match(r"^#\s+(.+?)\s*$", line)
        if m:
            return m.group(1).strip()
    return en_path.stem.replace("-", " ").title()


def _check_drift(out_dir: Path, expected: dict[str, tuple[str, str]], en_dir: Path) -> list[str]:
    """Return a list of (slug, reason) for stubs that would be regenerated
    or are missing. Used by --check in CI to catch out-of-band edits."""
    drift: list[str] = []
    for slug, (zh_title, _) in expected.items():
        en_path = en_dir / f"{slug}.md"
        zh_path = out_dir / f"{slug}.md"
        if not en_path.is_file():
            drift.append(f"{slug}: missing en source {en_path.relative_to(ROOT)}")
            continue
        if not zh_path.is_file():
            drift.append(f"{slug}: missing zh stub {zh_path.relative_to(ROOT)}")
            continue
        body = zh_path.read_text(encoding="utf-8")
        if GENERATED_MARKER not in body:
            drift.append(f"{slug}: zh page is hand-written, generator won't touch it")
            continue
        if not body.startswith(f"# {zh_title}\n"):
            drift.append(f"{slug}: zh H1 drifted from {zh_title!r}")
    return drift


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if any zh stub is missing or out of sync with the map",
    )
    args = parser.parse_args(argv)

    ZH_CS.mkdir(parents=True, exist_ok=True)
    ZH_EM.mkdir(parents=True, exist_ok=True)

    written = 0
    skipped = 0
    # Top-level pages (404, about, architecture, citation-graph, index)
    for slug, (zh_title, zh_desc) in TOP_LEVEL_PAGES.items():
        en_path = DOCS / f"{slug}.md"
        zh_path = DOCS / "zh" / f"{slug}.md"
        en_url = f"/{slug}" if slug != "index" else "/"
        # Special-case 404: en H1 is "404" with an emoji decoration
        en_title = _read_en_title(en_path) or slug.replace("-", " ").title()
        body = _render_stub("top", slug, zh_title, zh_desc, en_title, en_url)
        # Skip in BOTH modes if the target exists but is hand-written
        # (no marker). Hand-written pages are owned by humans.
        if zh_path.is_file() and GENERATED_MARKER.strip() not in zh_path.read_text(
            encoding="utf-8"
        ):
            skipped += 1
            continue
        if args.check:
            existing = zh_path.read_text(encoding="utf-8") if zh_path.is_file() else ""
            if existing != body:
                print(f"  drift: zh/{slug}.md", file=sys.stderr)
                return 1
        else:
            zh_path.parent.mkdir(parents=True, exist_ok=True)
            zh_path.write_text(body, encoding="utf-8")
            written += 1
    # Topic pages under papers/<area>/
    for slug, (zh_title, zh_desc) in CS_ZH.items():
        en_path = EN_CS / f"{slug}.md"
        zh_path = ZH_CS / f"{slug}.md"
        en_url = f"/papers/computer-science/{slug}"
        en_title = _read_en_title(en_path)
        body = _render_stub("cs", slug, zh_title, zh_desc, en_title, en_url)
        if args.check:
            existing = zh_path.read_text(encoding="utf-8") if zh_path.is_file() else ""
            if existing != body:
                print(f"  drift: zh/cs/{slug}.md", file=sys.stderr)
                return 1
        else:
            zh_path.write_text(body, encoding="utf-8")
            written += 1
    for slug, (zh_title, zh_desc) in EM_ZH.items():
        en_path = EN_EM / f"{slug}.md"
        zh_path = ZH_EM / f"{slug}.md"
        en_url = f"/papers/economics-management/{slug}"
        en_title = _read_en_title(en_path)
        body = _render_stub("em", slug, zh_title, zh_desc, en_title, en_url)
        if args.check:
            existing = zh_path.read_text(encoding="utf-8") if zh_path.is_file() else ""
            if existing != body:
                print(f"  drift: zh/em/{slug}.md", file=sys.stderr)
                return 1
        else:
            zh_path.write_text(body, encoding="utf-8")
            written += 1

    if args.check:
        print("[generate_zh_topic_stubs] all stubs up to date")
    else:
        print(
            f"[generate_zh_topic_stubs] wrote {written} zh stub(s), "
            f"skipped {skipped} hand-written page(s)"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
