"""Generate topic markdown pages from real metadata.json entries.

For Economics & Management: each topic page (e.g. ``human-resources.md``)
is rebuilt to list every paper that lives in
``papers/economics-management/<year>/<topic>/<...>``, sorted newest first.
Papers are rendered as a compact table (title → authors, year, journal,
DOI link).

For Computer Science: the source folder hierarchy exists but no
``metadata.json`` files live under ``papers/computer-science/`` yet. We
render the topic pages as an honest, intentional "0 papers indexed, ready
for contributions" notice, with the real sub-directory listing from the
filesystem so the structure is visible.

Run from the repo root:

    python3 scripts/generate_topic_pages.py
"""
