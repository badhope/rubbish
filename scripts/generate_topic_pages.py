def slugify(name: str) -> str:
    return name.lower()


def read_meta(meta_path: Path) -> dict | None:
    try:
        with open(meta_path, encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return None


def format_authors(meta: dict) -> str:
    authors = meta.get("authors") or []
    if isinstance(authors, str):
        return authors
    if not authors:
        return "—"
    if len(authors) <= 3:
        return ", ".join(authors)
    return f"{authors[0]} et al."


def paper_row(meta: dict) -> str:
    title = (meta.get("title") or "Untitled").strip().replace("|", "\\|")
    year = meta.get("year", "—")
    journal = (meta.get("journal") or "—").strip().replace("|", "\\|")
    doi = (meta.get("doi") or "").strip()
    doi_link = f"[{doi}](https://doi.org/{doi})" if doi else "—"

    # Build a "Read" cell that points to the best available copy:
    # 1) bundled PDF on the published site  2) publisher landing page
    # 3) DOI fallback
    if meta.get("has_pdf"):
        # _rel already starts with "papers/" (see line above), so don't prefix it again.
        # VitePress's `base: "/ScholarLib/"` is prepended automatically, yielding
        # https://badhope.github.io/ScholarLib/papers/<field>/.../paper.pdf
        read = f"[📄 PDF](/{meta['_rel']}/paper.pdf)"
    else:
        pub_url = (meta.get("publisher_url") or "").strip()
        if pub_url:
            read = f"[publisher]({pub_url})"
        elif doi:
            read = f"[doi](https://doi.org/{doi})"
        else:
            read = "—"

    return f"| [{title}]({REPO_URL}/tree/main/{meta['_rel']}) | {format_authors(meta)} | {year} | {journal} | {doi_link} | {read} |"


def pad_markdown_tables(text: str) -> str:
    """Pad Markdown table cells with spaces so column separators line up.

    Prettier reformats tables in this style; if we don't do it ourselves
    the auto-generated files would trip ``npm run format:check`` after
    every regeneration.
    """
    lines = text.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if "|" in line and i + 1 < len(lines) and re.match(r"^\s*\|?[\s:\-|]+\|?\s*$", lines[i + 1]):
            # collect the whole table block
            block: list[str] = [line]
            j = i + 1
            while j < len(lines) and lines[j].lstrip().startswith("|") and lines[j].strip().endswith("|"):
                block.append(lines[j])
                j += 1
            out.extend(_pad_table_block(block))
            i = j
            continue
        out.append(line)
        i += 1
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


def _pad_table_block(block: list[str]) -> list[str]:
    """Pad every cell in a Markdown table block to the column's max width."""
    rows: list[list[str]] = []
    for line in block:
        # drop leading/trailing pipes then split
        stripped = line.strip()
        if stripped.startswith("|"):
            stripped = stripped[1:]
        if stripped.endswith("|"):
            stripped = stripped[:-1]
        cells = [c.strip() for c in stripped.split("|")]
        rows.append(cells)
    if not rows or len(rows) < 2:
        return block
    n_cols = max(len(r) for r in rows)
    # pad shorter rows with empty cells
    for r in rows:
        if len(r) < n_cols:
            r.extend([""] * (n_cols - len(r)))
    # compute column widths excluding the separator row (index 1)
    widths = [0] * n_cols
    for idx, r in enumerate(rows):
        if idx == 1:  # separator
            continue
        for c, cell in enumerate(r):
            if len(cell) > widths[c]:
                widths[c] = len(cell)
    # also keep the separator row's `---` width at least 3
    for c in range(n_cols):
        widths[c] = max(widths[c], 3)
    rendered: list[str] = []
    for idx, r in enumerate(rows):
        if idx == 1:
            # rebuild separator with the same widths
            rendered.append("| " + " | ".join("-" * widths[c] for c in range(n_cols)) + " |")
        else:
            rendered.append("| " + " | ".join(r[c].ljust(widths[c]) for c in range(n_cols)) + " |")
    return rendered


# ── EM topic page ────────────────────────────────────────────────────
def render_em_field(field: str, pretty: str, papers_dir: Path | None = None) -> str:
    field_dir = papers_dir or (PAPERS / "economics-management")
    rel_root = field_dir.parent.parent  # one level above the discipline
    papers_by_year: dict[int, list[dict]] = defaultdict(list)
    for meta_path in sorted(field_dir.glob(f"*/{field}/**/metadata.json")):
        meta = read_meta(meta_path)
        if not meta:
            continue
        meta["_rel"] = str(meta_path.parent.relative_to(rel_root))
        year = int(meta.get("year", 0))
        papers_by_year[year].append(meta)

    # Discover which years have *any* subfolder for this field, so the
    # page reflects the directory layout (not just indexed papers).
    years_with_folder = sorted(
        {
            int(p.name)
            for p in field_dir.iterdir()
            if p.is_dir() and p.name.isdigit() and (p / field).exists()
        },
        reverse=True,
    )

    total = sum(len(v) for v in papers_by_year.values())
    header = (
        f"# {pretty}\n\n"
        f"{GENERATED_MARKER}"
        f"**{total}** indexed paper{'s' if total != 1 else ''}"
        f"{' across ' + str(len(years_with_folder)) + ' years' if years_with_folder else ''}."
        f"{' Folder structure present for ' + str(len(years_with_folder)) + ' year(s) (2020 – 2026).' if years_with_folder else ''}\n\n"
        f"> Source: `papers/economics-management/{{year}}/{field}/`\n\n"
    )

    body_parts: list[str] = []
    for year in sorted(papers_by_year.keys(), reverse=True):
        rows = sorted(papers_by_year[year], key=lambda m: m.get("title", "").lower())
        body_parts.append(f"## {year} · {len(rows)} paper{'s' if len(rows) != 1 else ''}\n")
        body_parts.append("| Title | Authors | Year | Journal | DOI | Read |")
        body_parts.append("| --- | --- | ---: | --- | --- | --- |")
        body_parts.extend(paper_row(m) for m in rows)
        body_parts.append("")

    if not papers_by_year:
        body_parts.append(
            "_No papers are indexed here yet. The folder structure is in place "
            "and ready for contributions — see [CONTRIBUTING.md]"
            f"({REPO_URL}/blob/main/CONTRIBUTING.md)._\n"
        )

    return header + "\n".join(body_parts).rstrip() + "\n"


def render_em_index() -> str:
    """The /papers/economics-management/ landing page."""
    fields_dir = PAPERS / "economics-management"
    counts: dict[str, int] = defaultdict(int)
    years_total: set[int] = set()
    for meta_path in sorted(fields_dir.glob("*/**/metadata.json")):
        meta = read_meta(meta_path)
        if not meta:
            continue
        cat = (meta.get("category") or "").strip().lower()
        if cat:
            counts[cat] += 1
        try:
            years_total.add(int(meta.get("year", 0)))
        except (TypeError, ValueError):
            pass

    # Discover year folders actually present on disk
    year_folders = sorted(
        (int(p.name) for p in fields_dir.iterdir() if p.is_dir() and p.name.isdigit()),
        reverse=True,
    )
    years_covered = year_folders or sorted(years_total, reverse=True)
    year_range = (
        f"{min(years_covered)} – {max(years_covered)}" if years_covered else "—"
    )
    n_fields = len(counts) or len(EM_PRETTY)

    rows: list[str] = []
    for slug in sorted(EM_PRETTY):
        n = counts.get(slug, 0)
        pretty = EM_PRETTY[slug]
        rows.append(
            f"| [{pretty}](/papers/economics-management/{slug}) | {n} |"
        )

    return (
        f"# Economics & Management\n\n"
        f"{GENERATED_MARKER}"
        f"**{sum(counts.values())}** indexed paper{'s' if sum(counts.values()) != 1 else ''} "
        f"across **{n_fields}** research fields, organized by publication year "
        f"({year_range}). Folder structure covers all fields for 2020 – "
        f"{max(years_covered) if years_covered else '2026'}.\n\n"
        "| Field | Papers |\n| --- | ---: |\n"
        + "\n".join(rows)
        + "\n\n## How Papers Are Organized\n\n"
        "Each field folder lives under "
        "`papers/economics-management/<year>/<field>/` and uses a 6-level "
        "taxonomy (Field → Topic → Journal Tier → Method → Scenario → Paper). "
        "Every paper ships a `metadata.json` and a `.bib` you can paste into "
        "LaTeX.\n"
    )


# ── CS topic page ────────────────────────────────────────────────────
def render_cs_topic(topic: str, pretty: str, papers_dir: Path | None = None) -> str:
    cs_root = papers_dir or (PAPERS / "computer-science")
    topic_dir = cs_root / topic
    subdirs: list[str] = []
    if topic_dir.exists():
        # 1st-level subfolders (e.g. Alignment, Interpretability)
        subdirs = sorted(
            p.name for p in topic_dir.iterdir() if p.is_dir() and not p.name.startswith(".")
        )
    return (
        f"# {pretty}\n\n"
        f"{GENERATED_MARKER}"
        f"Topic folder scaffolded with **{len(subdirs)}** sub-topic"
        f"{'s' if len(subdirs) != 1 else ''} — no papers indexed yet.\n\n"
        f"> Source folder: `papers/computer-science/{topic}/`\n\n"
        "This page is intentionally empty: the taxonomy is in place, the "
        "sub-folder structure is wired, and the moment a paper lands in "
        f"`papers/computer-science/{topic}/.../metadata.json` it will show up "
        "here. See the [CONTRIBUTING guide]"
        f"({REPO_URL}/blob/main/CONTRIBUTING.md) for the per-paper "
        "submission template.\n\n"
        + (
            "## Existing sub-topics\n\n"
            + "\n".join(f"- `{s}`" for s in subdirs)
            + "\n"
            if subdirs
            else ""
        )
    )


def render_cs_index() -> str:
    cs_dir = PAPERS / "computer-science"
    topics = sorted(
        p.name for p in cs_dir.iterdir() if p.is_dir() and not p.name.startswith(".")
    )
    rows = []
    for slug in CS_PRETTY:
        topic_dir = cs_dir / slug
        # Count placeholder years present (real signal that scaffolding is there)
        n_subdirs = (
            sum(1 for p in topic_dir.iterdir() if p.is_dir() and not p.name.startswith("."))
            if topic_dir.exists()
            else 0
        )
        rows.append(f"| [{CS_PRETTY[slug]}](/papers/computer-science/{slugify(slug)}) | {n_subdirs} |")
    return (
        f"# Computer Science\n\n"
        f"{GENERATED_MARKER}"
        f"Scaffolded **{len(topics)}** topics covering the CS landscape. "
        f"Papers haven't been indexed yet — the folder structure is in place "
        f"and waiting for the first submissions. Each topic follows the 6-level "
        f"taxonomy: Topic → Sub-area → Year → Method → Scenario → Paper.\n\n"
        "| Topic | Sub-areas scaffolded |\n| --- | ---: |\n"
        + "\n".join(rows)
        + "\n\n## How Papers Are Organized\n\n"
        "Each topic has its own sub-folder under `papers/computer-science/`. "
        "Inside a topic you'll find the area-level sub-folders (e.g. "
        "`Alignment/`, `Interpretability/`) and per-year READMEs that act as "
        "index files. The moment a paper lands in a topic folder with a "
        "matching `metadata.json`, the topic page lights up automatically.\n"
    )


# ── driver ───────────────────────────────────────────────────────────
def write(path: Path, content: str, *, force: bool = False) -> bool:
    """Write a generated file. Refuses to clobber a hand-edited page."""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if GENERATED_MARKER not in existing and not force:
            print(f"  skip (no marker, assumed hand-edited): {path.relative_to(ROOT)}")
            return False
    path.parent.mkdir(parents=True, exist_ok=True)
    # Pad Markdown table cells so the output passes ``npm run format:check``
    # without a separate ``prettier --write`` step.
    content = pad_markdown_tables(content)
    path.write_text(content, encoding="utf-8")
    return True


# ── per-paper leaf page ─────────────────────────────────────────────
def render_paper_leaf(meta: dict, *, source_rel: str) -> str:
    """Render a single paper as a VitePress page.

    ``source_rel`` is the path to the leaf folder relative to the repo
    root (e.g. ``papers/computer-science/.../imagenet-deep``). The page
    is emitted under ``docs/papers/...`` so VitePress builds it.
    """
    title = (meta.get("title") or "Untitled").strip()
    authors = meta.get("authors") or []
    if isinstance(authors, str):
        author_list = [a.strip() for a in authors.split(",") if a.strip()]
    else:
        author_list = [str(a).strip() for a in authors if str(a).strip()]
    year = meta.get("year", "—")
    journal = (meta.get("journal") or "—").strip()
    doi = (meta.get("doi") or "").strip()
    abstract = (meta.get("abstract") or "").strip()
    keywords = meta.get("keywords") or []
    publisher_url = (meta.get("publisher_url") or "").strip()
    bib_rel = source_rel  # e.g. "papers/.../imagenet-deep"
    paper_pdf_rel = f"{bib_rel}/paper.pdf"
    has_pdf = bool(meta.get("has_pdf"))

    author_inline = ", ".join(author_list) if author_list else "—"

    # Back-link: walk up the source path and find the nearest
    # topic page so the user can navigate back to the topic index.
    parts = source_rel.split("/")
    # "papers" "<field>" "<topic>" ... -> topic slug is parts[2]
    if len(parts) >= 3 and parts[0] == "papers":
        field = parts[1]
        topic_slug = parts[2].lower()
        back_href = f"/papers/{field}/{topic_slug}"
        back_label = "← Back to topic"
    else:
        back_href = "/"
        back_label = "← Home"

    doi_line = (
        f"**DOI:** [{doi}](https://doi.org/{doi})"
        if doi
        else "**DOI:** _not provided_"
    )
    publisher_line = (
        f"**Publisher:** [{publisher_url}]({publisher_url})"
        if publisher_url
        else ""
    )
    pdf_line = (
        f"**PDF:** [download]({paper_pdf_rel})"
        if has_pdf
        else ""
    )

    keywords_line = (
        f"\n**Keywords:** {', '.join(str(k).strip() for k in keywords if str(k).strip())}\n"
        if keywords
        else ""
    )
    abstract_block = (
        f"\n## Abstract\n\n{abstract}\n" if abstract else ""
    )

    bib_url = f"https://raw.githubusercontent.com/badhope/ScholarLib/main/{bib_rel}/paper.bib"
    meta_url = f"https://raw.githubusercontent.com/badhope/ScholarLib/main/{bib_rel}/metadata.json"

    return (
        f"# {title}\n\n"
        f"{GENERATED_MARKER}"
        f"{back_label}\n\n"
        f"**Authors:** {author_inline}  \n"
        f"**Year:** {year}  \n"
        f"**Journal:** {journal}  \n"
        f"{doi_line}  \n"
        f"{publisher_line}  \n"
        f"{pdf_line}\n"
        f"{keywords_line}"
        f"{abstract_block}"
        f"## Cite this paper\n\n"
        f"```bibtex\n"
        f"@misc{{{source_rel.split('/')[-1].lower().replace('-', '')}{year},\n"
        f"  title  = {{{title}}},\n"
        f"  author = {{{author_inline}}},\n"
        f"  year   = {{{year}}},\n"
        f"  journal = {{{journal}}},\n"
        f"  doi    = {{{doi}}},\n"
        f"  url    = {{https://doi.org/{doi}}},\n"
        f"}}\n"
        f"```\n\n"
        f"## Source files\n\n"
        f"- [`metadata.json`]({meta_url})\n"
        f"- [`paper.bib`]({bib_url})\n"
    )


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite hand-edited topic pages (still respects the marker check).",
    )
    args = parser.parse_args()

    written = 0
    skipped = 0

    # EM
    em_dir = DOCS / "economics-management"
    em_dir.mkdir(parents=True, exist_ok=True)
    for slug, pretty in EM_PRETTY.items():
        out = em_dir / f"{slugify(slug)}.md"
        if write(out, render_em_field(slug, pretty), force=args.force):
            written += 1
        else:
            skipped += 1
    if write(em_dir / "index.md", render_em_index(), force=args.force):
        written += 1
    else:
        skipped += 1

    # CS
    cs_dir = DOCS / "computer-science"
    cs_dir.mkdir(parents=True, exist_ok=True)
    for slug, pretty in CS_PRETTY.items():
        out = cs_dir / f"{slugify(slug)}.md"
        if write(out, render_cs_topic(slug, pretty), force=args.force):
            written += 1
        else:
            skipped += 1
    if write(cs_dir / "index.md", render_cs_index(), force=args.force):
        written += 1
    else:
        skipped += 1

    # Per-paper leaf pages: emit docs/papers/<full-path>/index.md for
    # every metadata.json so each paper has a VitePress page.
    paper_written = 0
    paper_skipped = 0
    for meta_path in sorted(PAPERS.glob("*/**/metadata.json")):
        meta = read_meta(meta_path)
        if not meta:
            continue
        # meta_path is .../papers/<field>/<...>/<leaf>/metadata.json
        leaf_dir = meta_path.parent
        # Mirror at docs/papers/<...>/<leaf>/index.md (relative to repo)
        rel_from_papers = leaf_dir.relative_to(PAPERS)  # <field>/<...>/<leaf>
        out = DOCS / rel_from_papers / "index.md"
        if write(out, render_paper_leaf(meta, source_rel=str(leaf_dir.relative_to(ROOT))), force=args.force):
            paper_written += 1
        else:
            paper_skipped += 1
    print(f"Wrote {written} topic page(s), skipped {skipped}.")
    print(f"Wrote {paper_written} per-paper page(s), skipped {paper_skipped}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
